export function t(key, language = document.documentElement.lang || 'en') {
  const sourceKey = aliases[key] || key;
  return translations[language]?.[sourceKey] ?? translations.en[sourceKey] ?? key;
}

export function setLanguage(language) {
  const selected = language === 'bn' ? 'bn' : 'en';
  document.documentElement.lang = selected;
  document.documentElement.dataset.lang = selected;
  localStorage.setItem('kolpotuli-language', selected);

  document.querySelectorAll('[data-i18n]').forEach(element => {
    element.textContent = t(element.dataset.i18n, selected);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
    element.placeholder = t(element.dataset.i18nPlaceholder, selected);
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
    element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel, selected));
  });

  window.dispatchEvent(new CustomEvent('kolpotuli-language-changed', { detail: { language: selected } }));
}

export function initLanguage() {
  const saved = localStorage.getItem('kolpotuli-language') || 'en';
  setLanguage(saved);
  return saved;
}
